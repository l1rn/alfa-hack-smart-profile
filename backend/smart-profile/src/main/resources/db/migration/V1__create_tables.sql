CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE applications
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    company_id      INTEGER,
    verification_id INTEGER,
    status          SMALLINT,
    CONSTRAINT pk_applications PRIMARY KEY (id)
);

CREATE TABLE companies
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(255),
    inn           VARCHAR(255),
    ogrn          VARCHAR(255),
    legal_address VARCHAR(255),
    revenue       BIGINT,
    user_id       INTEGER,
    CONSTRAINT pk_companies PRIMARY KEY (id)
);

CREATE TABLE credit_products
(
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title           VARCHAR(255),
    min_amount      BIGINT,
    max_amount      BIGINT,
    min_term_months INTEGER,
    max_term_months INTEGER,
    interest_rate   DOUBLE PRECISION,
    CONSTRAINT pk_creditproducts PRIMARY KEY (id)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE users
(
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email    VARCHAR(255)                             NOT NULL,
    password VARCHAR(255)                             NOT NULL,
    phone    VARCHAR(255),
    role     VARCHAR(255)                             NOT NULL,
    enabled  BOOLEAN                                  NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE verifications
(
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    egrul_status      VARCHAR(255),
    bki_status        VARCHAR(255),
    final_verdict     VARCHAR(255),
    issue_date        TIMESTAMP(6) WITHOUT TIME ZONE,
    credit_product_id INTEGER,
    CONSTRAINT pk_verifications PRIMARY KEY (id)
);

ALTER TABLE companies
    ADD CONSTRAINT uc_companies_userid UNIQUE (user_id);

ALTER TABLE users
    ADD CONSTRAINT uc_users_email UNIQUE (email);

ALTER TABLE applications
    ADD CONSTRAINT FK_APPLICATIONS_ON_COMPANYID FOREIGN KEY (company_id) REFERENCES companies (id);

ALTER TABLE applications
    ADD CONSTRAINT FK_APPLICATIONS_ON_VERIFICATIONID FOREIGN KEY (verification_id) REFERENCES verifications (id);

ALTER TABLE companies
    ADD CONSTRAINT FK_COMPANIES_ON_USERID FOREIGN KEY (user_id) REFERENCES users (id);

ALTER TABLE revchanges
    ADD CONSTRAINT fk_revchanges_on_default_tracking_modified_entities_changelog FOREIGN KEY (rev) REFERENCES revinfo (rev);